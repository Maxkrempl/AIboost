let currentLang = localStorage.getItem('menuboost_lang') || 'sl';

function t(key) {
  var val = (I18N[currentLang] || I18N['sl'])[key];
  return val !== undefined ? val : (I18N['sl'])[key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('menuboost_lang', lang);
  applyTranslations();
}

function applyTranslations() {
  // Language switch button + dropdown active state
  var langToggle = document.getElementById('lang-toggle');
  if (langToggle && LANG_LABELS[currentLang]) langToggle.innerHTML = LANG_LABELS[currentLang] + ' ▾';
  document.querySelectorAll('.lang-option').forEach(function(opt) {
    opt.classList.toggle('active', opt.dataset.lang === currentLang);
  });
  // Badge
  var badge = document.querySelector('.header-badge');
  if (badge) badge.textContent = t('badge');
  // Hero
  var eyebrow = document.querySelector('.hero-eyebrow');
  if (eyebrow) eyebrow.textContent = t('eyebrow');
  var h1 = document.querySelector('.hero h1');
  if (h1) h1.innerHTML = t('heroTitle');
  var heroP = document.querySelector('.hero p');
  if (heroP) heroP.textContent = t('heroDesc');
  // Empty state
  var emptyText = document.getElementById('empty-text');
  if (emptyText) emptyText.innerHTML = t('emptyState');
  // Dish section label
  var cardLabel = document.querySelector('.card-label');
  if (cardLabel) cardLabel.textContent = t('dishSection');
  // Form labels
  var labels = document.querySelectorAll('label');
  if (labels[0]) labels[0].textContent = t('dishName');
  if (labels[1]) labels[1].textContent = t('ingredients');
  if (labels[2]) labels[2].textContent = t('restType');
  if (labels[3]) labels[3].textContent = t('styleLabel');
  if (labels[4]) labels[4].textContent = t('langLabel');
  // Placeholders (dynamic dish rows)
  document.querySelectorAll('.dish-name').forEach(function(el){ el.placeholder = t('dishPlaceholder'); });
  document.querySelectorAll('.dish-ingredients').forEach(function(el){ el.placeholder = t('ingredientsPlaceholder'); });
  // Dish row labels
  document.querySelectorAll('.dish-name').forEach(function(el){ var l=el.parentElement.querySelector('label'); if(l) l.textContent=t('dishName'); });
  document.querySelectorAll('.dish-ingredients').forEach(function(el){ var l=el.parentElement.querySelector('label'); if(l) l.textContent=t('ingredients'); });
  // Restaurant type options
  var sel = document.getElementById('rest-type');
  if (sel) {
    var types = t('restTypes');
    Array.from(sel.options).forEach(function(opt) {
      if (types[opt.value]) opt.textContent = types[opt.value];
    });
  }
  // Style pills
  var styles = t('styles');
  document.querySelectorAll('.style-pill').forEach(function(pill) {
    var s = pill.dataset.style;
    if (styles[s]) pill.textContent = styles[s];
  });
  // Buttons
  var btnText = document.getElementById('btn-text');
  var generatingTexts = ['Ustvarjam...','Generating...','Kreiram...','Genero...','Erstelle...','Génération...','Generando...','Oluşturuluyor...','Δημιουργία...'];
  var regenerateTexts = ['Ustvari znova','Generate again','Kreiraj ponovno','Genera di nuovo','Erneut generieren','Générer à nouveau','Generar de nuevo','Tekrar oluştur','Δημιουργία ξανά'];
  if (btnText) {
    if (generatingTexts.indexOf(btnText.textContent) === -1) {
      btnText.textContent = regenerateTexts.indexOf(btnText.textContent) !== -1 ? t('btnRegenerate') : t('btnGenerate');
    }
  }
  // Add dish button
  var addBtn = document.getElementById('btn-add-dish');
  if (addBtn) addBtn.textContent = t('btnAddDish');
  // Credits
  var creditsLabel = document.querySelector('.credits-row span');
  if (creditsLabel) creditsLabel.innerHTML = t('creditsFree') + ' <strong id="credits-num">' + credits + '</strong>';
  var banner = document.getElementById('no-credits-banner');
  if (banner) banner.innerHTML = t('creditsUsed') + ' <a onclick="checkout()">' + t('creditsUpgrade') + '</a>';
  // QR section
  var qrTitle = document.querySelector('.qr-section h3');
  if (qrTitle) qrTitle.textContent = t('qrTitle');
  var qrSub = document.querySelector('.qr-subtitle');
  if (qrSub) qrSub.textContent = t('qrSubtitle');
  var qrWorks = document.querySelector('.qr-section p[style]');
  if (qrWorks) qrWorks.textContent = t('qrWorks');
  // QR buttons
  var qrBtns = document.querySelectorAll('.btn-qr');
  if (qrBtns[0]) qrBtns[0].textContent = '📥 ' + t('qrDownload');
  if (qrBtns[1]) qrBtns[1].textContent = '📄 ' + t('qrPdf');
  if (qrBtns[2]) qrBtns[2].textContent = '🔗 ' + t('qrCopyLink');
  // Upgrade card
  var upH3 = document.querySelector('.upgrade-text h3');
  if (upH3) upH3.textContent = t('upgradeTitle');
  var upP = document.querySelector('.upgrade-text p');
  if (upP) upP.textContent = t('upgradeDesc');
  var upBtn = document.querySelector('.btn-upgrade');
  if (upBtn) upBtn.textContent = t('upgradeBtn');
  // SEO
  var seoH2 = document.querySelector('.seo-content h2');
  if (seoH2) seoH2.textContent = t('seoTitle');
  var seoPs = document.querySelectorAll('.seo-content > p');
  if (seoPs[0]) seoPs[0].textContent = t('seoP1');
  if (seoPs[1]) seoPs[1].textContent = t('seoP2');
  var faqH3 = document.querySelector('.seo-content h3');
  if (faqH3) faqH3.textContent = t('faqTitle');
  // FAQ
  var faqItems = document.querySelectorAll('.faq-item');
  var faqKeys = [['faq1q','faq1a'],['faq2q','faq2a'],['faq3q','faq3a'],['faq4q','faq4a'],['faq5q','faq5a']];
  faqItems.forEach(function(item, i) {
    if (faqKeys[i]) {
      var q = item.querySelector('.faq-q');
      var a = item.querySelector('.faq-a');
      if (q) q.textContent = t(faqKeys[i][0]);
      if (a) a.textContent = t(faqKeys[i][1]);
    }
  });
  // Copy buttons
  document.querySelectorAll('.btn-copy').forEach(function(btn) { btn.textContent = t('copy'); });
  // Update HTML lang
  document.documentElement.lang = currentLang;
}
