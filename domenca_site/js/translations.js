function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (translations[lang][key].includes('<')) {
        el.innerHTML = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });
  document.documentElement.lang = lang === 'si' ? 'sl' : lang;
  const btn = document.getElementById('langToggle');
  if (btn) btn.textContent = translations[lang]['lang.selector'] || lang.toUpperCase();
}

const LANG_ORDER = ['si', 'en', 'hr', 'de', 'it'];

function toggleLanguage() {
  const current = localStorage.getItem('hd-lang') || 'en';
  const idx = LANG_ORDER.indexOf(current);
  const next = LANG_ORDER[(idx + 1) % LANG_ORDER.length];
  localStorage.setItem('hd-lang', next);
  applyTranslations(next);
}

function detectLanguage() {
  const saved = localStorage.getItem('hd-lang');
  if (saved && LANG_ORDER.includes(saved)) return saved;
  const browserLang = navigator.language || navigator.userLanguage || '';
  const langCode = browserLang.split('-')[0];
  if (langCode === 'sl') return 'si';
  if (LANG_ORDER.includes(langCode)) return langCode;
  return 'en';
}

document.addEventListener('DOMContentLoaded', () => {
  const lang = detectLanguage();
  localStorage.setItem('hd-lang', lang);
  applyTranslations(lang);
});
